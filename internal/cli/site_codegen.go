package cli

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	hex "github.com/crazycatviking/hex/server"
	"github.com/spf13/cobra"
)

func (a *App) siteActionCodegenCommand(options *siteCommandOptions) *cobra.Command {
	var output, catalog string
	var check bool
	command := &cobra.Command{Use: "codegen", Short: "Generate version-pinned TypeScript wrappers for a site's exported actions", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, args []string) error {
		if check && output == "" {
			return errors.New("--check requires --out")
		}
		var data []byte
		var err error
		if catalog != "" {
			if err := validateSiteName(options.site); err != nil {
				return err
			}
			data, err = readLimitedFile(resolvePath(a.Dir, catalog), 4<<20)
		} else {
			project, configError := options.config(a)
			if configError != nil {
				return configError
			}
			data, err = a.apiRequest(cmd.Context(), project, "/api/sites/"+options.site+"/actions")
		}
		if err != nil {
			return err
		}
		var definitions []hex.ActionDefinition
		if err := json.Unmarshal(data, &definitions); err != nil {
			return err
		}
		generated, err := generateSiteActionModule(options.site, definitions)
		if err != nil {
			return err
		}
		if output == "" {
			_, err := a.Out.Write(generated)
			return err
		}
		path := resolvePath(a.Dir, output)
		if check {
			existing, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(existing, generated) {
				return fmt.Errorf("%s is out of date; rerun hex actions codegen", output)
			}
			return nil
		}
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		return atomicWrite(path, generated, 0644)
	}}
	command.Flags().StringVar(&output, "out", "", "Generated TypeScript file (default: stdout)")
	command.Flags().StringVar(&catalog, "catalog", "", "Saved actions list JSON; requires --site")
	command.Flags().BoolVar(&check, "check", false, "Check the generated file without writing")
	return command
}

func generateSiteActionModule(site string, definitions []hex.ActionDefinition) ([]byte, error) {
	if err := validateSiteName(site); err != nil {
		return nil, err
	}
	definitions = slices.Clone(definitions)
	slices.SortFunc(definitions, func(a, b hex.ActionDefinition) int { return strings.Compare(a.Name, b.Name) })
	types := newTypeScriptTypes()
	var methods strings.Builder
	names := map[string]bool{}
	for _, definition := range definitions {
		if !definition.Exported {
			continue
		}
		if definition.Version < 1 {
			return nil, errors.New("exported action lacks a version")
		}
		if err := definition.ValidateSchemas(); err != nil {
			return nil, err
		}
		base := pascalCase(definition.Name)
		if names[base] {
			return nil, fmt.Errorf("action names collide in TypeScript: %s", definition.Name)
		}
		names[base] = true
		if _, err := types.declare(base+"Input", "Input for "+definition.Name, definition.InputSchema); err != nil {
			return nil, err
		}
		if _, err := types.declare(base+"Output", "Output for "+definition.Name, definition.OutputSchema); err != nil {
			return nil, err
		}
		options := "options: { idempotencyKey: string }"
		if definition.ReadOnly {
			options = "options: { idempotencyKey?: string } = {}"
		}
		methods.WriteString(docComment(definition.Description, 2))
		fmt.Fprintf(&methods, "    %s(input: %sInput, %s): Promise<%sOutput> {\n", strconv.Quote(definition.Name), base, options, base)
		fmt.Fprintf(&methods, "      return sites.api(%s, { version: %d }).call<%sOutput>(%s, input, options);\n    },\n", strconv.Quote(site), definition.Version, base, strconv.Quote(definition.Name))
	}
	if len(names) == 0 {
		return nil, errors.New("site has no visible exported actions")
	}
	var module strings.Builder
	module.WriteString("// Generated by hex actions codegen. Do not edit; exclude from formatters.\n")
	module.WriteString("export interface SiteAPICaller {\n  api(target: string, options: { version: number }): {\n    call<T>(action: string, input: unknown, options?: { idempotencyKey?: string }): Promise<T>;\n  };\n}\n")
	for _, declaration := range types.declarations {
		module.WriteString("\n" + declaration)
	}
	module.WriteString("\nexport function typedSiteAPI(sites: SiteAPICaller) {\n  return {\n")
	module.WriteString(methods.String())
	module.WriteString("  };\n}\n")
	return []byte(module.String()), nil
}
